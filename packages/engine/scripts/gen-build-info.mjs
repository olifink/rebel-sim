#!/usr/bin/env node
// Regenerates src/build-info.ts with the current local time, stamping
// this exact compile — run automatically as `pretest`/`prebuild` (npm's
// own lifecycle-hook naming, not a hand-wired call site) so every real
// entry point (vitest, tsc) always sees a fresh file. The output is
// gitignored on purpose: baking in *when this build happened* is the
// whole point, so a stale committed copy would defeat it — see VERSION
// (primitives.ts) for the one thing that reads this.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const now = new Date();
const pad = (n) => String(n).padStart(2, '0');
// YYMMDD-HHmm: compact enough to sit as one version segment, still
// eyeball-readable, minute granularity so a same-day rebuild during fast
// browser-refresh-speed iteration still reads as a distinct build.
const stamp =
  `${pad(now.getFullYear() % 100)}${pad(now.getMonth() + 1)}${pad(now.getDate())}` +
  `-${pad(now.getHours())}${pad(now.getMinutes())}`;

const outPath = join(dirname(fileURLToPath(import.meta.url)), '../src/build-info.ts');
writeFileSync(
  outPath,
  `// Auto-generated by scripts/gen-build-info.mjs on every build — do not
// hand-edit, do not commit (gitignored). VERSION (primitives.ts) reads
// this single stamp to tell a freshly built page apart from a stale
// cached one.
export const BUILD_STAMP = '${stamp}';
`,
);
